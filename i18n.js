const SUPPORTED    = ['en','fr','tr'];
const DEFAULT_LANG = 'en';
const STORAGE_KEY  = 'timbi_lang';
const FLAGS = { en:'🇬🇧', fr:'🇫🇷', tr:'🇹🇷' };
const CODES = { en:'EN',   fr:'FR',   tr:'TR'  };

function detectLang() {
  const saved   = localStorage.getItem(STORAGE_KEY);
  if (saved && SUPPORTED.includes(saved)) return saved;
  const browser = (navigator.language || '').slice(0,2).toLowerCase();
  return SUPPORTED.includes(browser) ? browser : DEFAULT_LANG;
}

function applyTranslations(lang) {
  const t = translations[lang];
  if (!t) return;

  /* text content */
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const v = t[el.dataset.i18n];
    if (v !== undefined) el.textContent = v;
  });

  /* placeholders */
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const v = t[el.dataset.i18nPh];
    if (v !== undefined) el.placeholder = v;
  });

  /* select options */
  document.querySelectorAll('select option[data-i18n]').forEach(opt => {
    const v = t[opt.dataset.i18n];
    if (v !== undefined) opt.textContent = v;
  });

  /* html lang */
  document.documentElement.lang = lang;

  /* switcher UI */
  const flagEl = document.getElementById('currentFlag');
  const codeEl = document.getElementById('currentCode');
  if (flagEl) flagEl.textContent = FLAGS[lang];
  if (codeEl) codeEl.textContent = CODES[lang];

  document.querySelectorAll('.lang-option').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
}

function switchLang(lang) {
  if (!SUPPORTED.includes(lang)) return;
  const main = document.getElementById('mainContent');
  if (main) {
    main.style.transition = 'opacity .18s ease';
    main.style.opacity = '0';
  }
  setTimeout(() => {
    applyTranslations(lang);
    localStorage.setItem(STORAGE_KEY, lang);
    if (main) main.style.opacity = '1';
  }, 180);
}

/* Public API used by script.js */
window.getCurrentLang = () => localStorage.getItem(STORAGE_KEY) || DEFAULT_LANG;
window.getTranslation  = key => {
  const lang = window.getCurrentLang();
  return (translations[lang] && translations[lang][key]) || '';
};

/* Init */
document.addEventListener('DOMContentLoaded', () => {
  const lang      = detectLang();
  const switcher  = document.getElementById('langSwitch');
  const toggle    = document.getElementById('langToggle');

  applyTranslations(lang);

  if (toggle) {
    toggle.addEventListener('click', e => {
      e.stopPropagation();
      const open = switcher.classList.toggle('open');
      toggle.setAttribute('aria-expanded', open);
    });
  }

  document.addEventListener('click', () => {
    switcher?.classList.remove('open');
    toggle?.setAttribute('aria-expanded','false');
  });

  document.querySelectorAll('.lang-option').forEach(btn => {
    btn.addEventListener('click', e => {
      e.stopPropagation();
      switchLang(btn.dataset.lang);
      switcher?.classList.remove('open');
      toggle?.setAttribute('aria-expanded','false');
    });
  });
});
